// A roster rig's backWaist and backSell live in two places that must agree (PLAN_GEORGE_TRANSFER rules): the generator's
// SPECS entry (tools/wrestler-cutter/prepare-roster-character.py) and the generated src/characters file, which
// is edited by hand rather than regenerated so Derek's tuner edits survive. A rig with no `backWaist=` in its
// SPECS entry must have none in its file; likewise `backSell=`.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { georgeRosterV1 } from '../src/characters/george_roster_v1.js';
import { kowalskiRosterV1 } from '../src/characters/kowalski_roster_v1.js';
import { guidoRosterV1 } from '../src/characters/guido_roster_v1.js';
import { theszRosterV1 } from '../src/characters/thesz_roster_v1.js';

const GENERATED = { george: georgeRosterV1, kowalski: kowalskiRosterV1, guido: guidoRosterV1 };
const py = readFileSync(new URL('../tools/wrestler-cutter/prepare-roster-character.py', import.meta.url), 'utf8');
const specs = Object.fromEntries([...py.matchAll(/^ '(\w+)':dict\(/gm)].map((m, i, all) =>
    [m[1], py.slice(m.index, all[i + 1]?.index ?? py.indexOf('\n}\n', m.index))]));
const specBackWaist = text => { const m = text.match(/backWaist=\{'u':([\d.]+),'v':([\d.]+)\}/); return m ? { u: +m[1], v: +m[2] } : null; };

const specBackSell = text => { const m = text.match(/backSell=(\{(?:[^{}]|\{(?:[^{}]|\{[^{}]*\})*\})*\})/); return m ? JSON.parse(m[1].replace(/'/g, '"').replace(/:True/g, ':true').replace(/:False/g, ':false')) : null; };

test('the generator SPECS and the generated file give every roster rig the same backSell (or none)', () => {
    for (const [name, rig] of Object.entries(GENERATED))
        assert.deepEqual(rig.textures.backSell ?? null, specBackSell(specs[name]), `${name}: generated file vs SPECS`);
});

test('the generator SPECS and the generated file give every roster rig the same backWaist (or none)', () => {
    assert.deepEqual(Object.keys(specs).sort(), Object.keys(GENERATED).sort());
    for (const [name, rig] of Object.entries(GENERATED)) {
        const fromSpec = specBackWaist(specs[name]);
        const fromFile = rig.textures.torso.semanticAnchors?.backWaist ?? null;
        assert.deepEqual(fromFile, fromSpec, `${name}: generated file vs SPECS`);
    }
});

test('George has backWaist candidate A (Rev 2 D6, on the contour; G6a had picked C) and his backSell re-measured there (T6.4), holdW .7 for the route through aroundVia (T8.3)', () => {
    assert.deepEqual(georgeRosterV1.textures.torso.semanticAnchors, { backWaist: { u: 0.2558, v: 0.6077 } });
    const b = georgeRosterV1.textures.backSell;
    assert.deepEqual({ ...b, evidence: undefined }, { holdW: 0.7, recoveryArm: -0.7, recoveryElbow: 1.1, settledElbow: 0.7, contactPx: 15, handUnder: true, aroundVia: { u: -0.4772, v: 0.6358, recoveryArm: -0.45, recoveryElbow: -1.8, approach: 0.4, path: [{ u: -0.4772, v: 0.6358 }] }, evidence: undefined });
    assert.match(b.evidence, /hold_weight_sweep/);
    assert.match(b.evidence, /recovery_probe/);
    assert.match(b.evidence, /around_via_candidates/);
    assert.match(b.evidence, /around_recovery_probe/);
    assert.match(b.evidence, /holdW \.45 -> \.7/);
    assert.match(b.evidence, /PLAN_GETUPS T2\.9/, 'the T2.9 re-registration of aroundVia is recorded in the evidence');
});

test('the generator writes the anchor into the torso and nothing else is touched by it', () => {
    assert.match(py, /if SPEC\.get\('backSell'\):textures\['backSell'\]=dict\(SPEC\['backSell'\]\)/);
    assert.match(py, /if SPEC\.get\('backWaist'\):textures\['torso'\]=dict\(textures\['torso'\],semanticAnchors=\{'backWaist':SPEC\['backWaist'\]\}\)/);
    assert.equal(theszRosterV1.textures.torso.semanticAnchors, undefined, 'thesz-roster-v1 is not generated by this script');
});
