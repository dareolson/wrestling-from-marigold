// Who has which move, from the code. For every registry id: kit-gated or not, the roster kits holding it
// (src/characters/rosterKits.js), the slot it competes in (KIT_SLOTS) and its coverage status.
//
//   npm run moves:kits             print the table
//   npm run moves:kits -- --check  fail if the marked block in MOVE_CATALOG.md differs from it
//   npm run moves:kits -- --write  rewrite that block
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { MOVE_IDS, MOVE_SPECS, KIT_SLOTS } from '../../src/moves/registry.js';
import { ROSTER_KITS } from '../../src/characters/rosterKits.js';
import { buildCoverage } from './coverage.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
export const CATALOG_PATH = resolve(ROOT, 'MOVE_CATALOG.md');
export const BEGIN = '<!-- moves:kits begin (generated by `npm run moves:kits -- --write`; do not edit by hand) -->';
export const END = '<!-- moves:kits end -->';

const WHO = { thesz: 'Lou', george: 'George', kowalski: 'Kowalski', guido: 'Guido' };

/** One row per registry id. */
export function kitRows({ kits = ROSTER_KITS, ids = MOVE_IDS, specs = MOVE_SPECS, slots = KIT_SLOTS,
    coverage = buildCoverage() } = {}) {
    const status = new Map(coverage.moves.map(m => [m.id, m.status]));
    return ids.map(id => ({
        id,
        kitGated: !!specs[id].kitGated,
        kits: Object.keys(kits).filter(k => kits[k].includes(id)).map(k => WHO[k] ?? k),
        slot: Object.entries(slots).find(([, order]) => order.includes(id))?.[0] ?? '',
        coverage: status.get(id) ?? '?',
    }));
}

/** The marked block, markers included, no trailing newline. */
export function kitsBlock(rows = kitRows()) {
    const lines = [BEGIN, '', '| Move | Kit-gated | Kits holding it | Slot | Coverage |', '|---|---|---|---|---|'];
    for (const r of rows) {
        lines.push(`| \`${r.id}\` | ${r.kitGated ? 'yes' : 'no'} | ${r.kitGated ? (r.kits.join(', ') || 'none') : 'everyone'} | ${r.slot || '-'} | ${r.coverage} |`);
    }
    lines.push('', END);
    return lines.join('\n');
}

const BLOCK = new RegExp(`${BEGIN.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`);

/** { ok, reason } comparing the catalog's marked block with the generated one. */
export function checkCatalog(text = readFileSync(CATALOG_PATH, 'utf8'), block = kitsBlock()) {
    const found = text.match(BLOCK)?.[0];
    if (!found) return { ok: false, reason: 'MOVE_CATALOG.md has no moves:kits block' };
    if (found !== block) return { ok: false, reason: 'the moves:kits block in MOVE_CATALOG.md is out of date; run `npm run moves:kits -- --write`' };
    return { ok: true };
}

function main(argv) {
    const block = kitsBlock();
    if (argv.includes('--write')) {
        const text = readFileSync(CATALOG_PATH, 'utf8');
        if (!BLOCK.test(text)) { console.error('MOVE_CATALOG.md has no moves:kits markers'); process.exitCode = 1; return; }
        writeFileSync(CATALOG_PATH, text.replace(BLOCK, () => block));
        console.log('rewrote the moves:kits block in MOVE_CATALOG.md');
        return;
    }
    console.log(block);
    if (argv.includes('--check')) {
        const r = checkCatalog(undefined, block);
        if (!r.ok) { console.error(`FAIL: ${r.reason}`); process.exitCode = 1; } else console.log('\nmoves:kits --check passed');
    }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main(process.argv.slice(2));
